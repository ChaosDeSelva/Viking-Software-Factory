// Embeds content/*.md as strings in src/generated/content.ts so tsc can emit them.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "content");
const pages = {};
for (const file of readdirSync(dir).sort()) {
  if (!file.endsWith(".md")) continue;
  pages[file.slice(0, -3)] = readFileSync(join(dir, file), "utf8");
}
const out = join(root, "src", "generated");
mkdirSync(out, { recursive: true });
const body =
  "// Generated by scripts/embed-content.mjs from content/*.md. Do not edit.\n" +
  `export const RAW_PAGES: Readonly<Record<string, string>> = ${JSON.stringify(pages, null, 2)};\n`;
const target = join(out, "content.ts");
let previous = "";
try {
  previous = readFileSync(target, "utf8");
} catch {
  // first run
}
if (previous !== body) writeFileSync(target, body);
