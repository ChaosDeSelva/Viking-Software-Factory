// Generates docs/api.md from packages/protocol/openapi.json.
// Usage: node scripts/generate-api-docs.mjs [--stdout]   (default writes docs/api.md)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(root, "packages/protocol/openapi.json"), "utf8"));

// Every operation in openapi.json is served by apps/server/src/routes (checked by
// scripts/api-docs.test.mjs). These routes are served too but are not part of the generated
// OpenAPI contract, so the SDK does not cover them.
const EXTRA = [
  [
    "POST",
    "/v1/missions/{id}/pause",
    "Move a running mission to `paused` (mission state only: agent sessions are not paused, the runtime has no pause). Body: optional `expectedVersion`. 202 OperationAccepted.",
  ],
  [
    "POST",
    "/v1/missions/{id}/resume",
    "Resume a paused mission. Body: optional `expectedVersion`. 202 OperationAccepted.",
  ],
  [
    "POST",
    "/v1/tasks/{id}/pr",
    "Request a pull request for a task. `pr.create` is gated by policy: the response is `status: approval_required` with an `approvalId` until a human approves, then `delivered`. Uses the `gh` CLI. 202 OperationAccepted.",
  ],
  [
    "GET",
    "/v1/sessions/{id}/terminal",
    "Terminal text of a session as the runtime shows it now (query `lines`). Secrets are redacted. Display only, never a state source. `capability_unavailable` (501) when the runtime cannot read terminals.",
  ],
  [
    "GET",
    "/v1/attention",
    "What needs a human: pending approvals, tasks blocked too long, sessions with no observed change, budgets at their warning fraction or exhausted.",
  ],
];

const ref = (s) => s.$ref.split("/").pop();
function type(s) {
  if (!s) return "any";
  if (s.$ref) return `[${ref(s)}](#${ref(s).toLowerCase()})`;
  if (s.enum) return s.enum.map((v) => `\`${v}\``).join(" \\| ");
  if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).map(type).join(" \\| ");
  if (s.type === "array") return `${type(s.items)}[]`;
  if (s.type === "object" && s.properties) return "object";
  if (s.type === "object") return "object";
  if (Array.isArray(s.type)) return s.type.join(" \\| ");
  const bits = [s.type ?? "any"];
  if (s.minLength) bits.push(`min ${s.minLength}`);
  if (s.minimum !== undefined) bits.push(`min ${s.minimum}`);
  if (s.maximum !== undefined) bits.push(`max ${s.maximum}`);
  if (s.default !== undefined) bits.push(`default ${JSON.stringify(s.default)}`);
  return bits.join(", ");
}
const esc = (t) => (t ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function fields(s) {
  if (!s || s.$ref || !s.properties) return null;
  const req = new Set(s.required ?? []);
  const rows = ["| Field | Type | Required | Notes |", "|---|---|---|---|"];
  for (const [k, v] of Object.entries(s.properties)) {
    rows.push(`| \`${k}\` | ${type(v)} | ${req.has(k) ? "yes" : "no"} | ${esc(v.description)} |`);
  }
  return rows.join("\n");
}

const out = [];
out.push("# HTTP API", "");
out.push(
  "<!-- Generated by scripts/generate-api-docs.mjs from packages/protocol/openapi.json. Do not edit by hand. -->",
  "",
);
out.push(`${spec.info.description}`, "");
out.push(
  `Contract version ${spec.info.version}. Base path \`/v1\`. The contract is generated from the Zod schemas in \`packages/protocol\`.`,
  "",
  "## Conventions",
  "",
  "- Every `/v1/*` route except `GET /v1/health` needs `Authorization: Bearer <token>` (`mimir token show`).",
  "- Mutations need an `Idempotency-Key` header (422 without it). Replaying a key returns the original result with `Idempotency-Replayed: true`; reusing a key with a different body is a 409.",
  "- Errors use `ApiErrorBody` (see [schemas](#schemas)).",
  "- Event ordering is per stream only. There is no global order.",
  "- A browser `Origin` that is not the server's own origin or in `MIMIR_ALLOWED_ORIGINS` is rejected, as is a `Host` the server does not recognise.",
  "",
  "## Served routes",
  "",
  "The server serves every route in the contract below, plus the extra routes listed after the table. With `mimir start` (or `MIMIR_WEB_ROOT`) it also serves the built web app on the same origin for `GET` and `HEAD` outside `/v1`; that part needs no token.",
  "",
  "| Route | Status |",
  "|---|---|",
);
const ops = [];
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(methods))
    ops.push({ path, method: method.toUpperCase(), op });
}
for (const { path, method } of ops) out.push(`| \`${method} ${path}\` | served |`);
for (const [method, path] of EXTRA)
  out.push(`| \`${method} ${path}\` | served, not in the OpenAPI contract |`);
out.push("", "## Extra routes (not in the OpenAPI contract)", "");
for (const [method, path, text] of EXTRA) out.push(`- \`${method} ${path}\`: ${text}`);
out.push("", "## Operations", "");
for (const { path, method, op } of ops) {
  out.push(`### ${method} ${path}`, "", `${op.summary}`, "");
  out.push("Status: served", "");
  if (op.parameters?.length) {
    out.push("| Parameter | In | Type | Required | Notes |", "|---|---|---|---|---|");
    for (const p of op.parameters) {
      out.push(
        `| \`${p.name}\` | ${p.in} | ${type(p.schema)} | ${p.required ? "yes" : "no"} | ${esc(p.description ?? p.schema?.description)} |`,
      );
    }
    out.push("");
  }
  const body = op.requestBody?.content?.["application/json"]?.schema;
  if (body) {
    out.push("Request body:", "", fields(body) ?? `${type(body)}`, "");
  }
  out.push("Responses:", "");
  for (const [code, r] of Object.entries(op.responses)) {
    const content = r.content ?? {};
    const mt = Object.keys(content)[0];
    const sch = mt ? content[mt].schema : undefined;
    out.push(
      `- \`${code}\` ${esc(r.description)}${mt ? ` (${mt})` : ""}${sch?.$ref ? `: ${type(sch)}` : ""}`,
    );
    const f = fields(sch);
    if (f) out.push("", f, "");
  }
  out.push("");
}
out.push("## Schemas", "");
for (const [name, s] of Object.entries(spec.components?.schemas ?? {})) {
  out.push(`### ${name}`, "");
  if (s.description) out.push(esc(s.description), "");
  out.push(fields(s) ?? `Type: ${type(s)}`, "");
}
const text =
  out
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd() + "\n";
if (process.argv.includes("--stdout")) process.stdout.write(text);
else writeFileSync(join(root, "docs/api.md"), text);
