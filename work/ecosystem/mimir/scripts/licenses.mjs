// pnpm licenses:check
// Walks the installed dependency tree (`pnpm licenses list --json`) and applies the license policy:
//   allowed:       Apache-2.0, MIT, BSD-2-Clause, BSD-3-Clause, ISC, 0BSD, Unlicense, CC0-1.0,
//                  BlueOak-1.0.0, Python-2.0, Zlib (plus MIT-0, a strictly more permissive MIT; see docs/licenses.md)
//   dev-only:      MPL-2.0 (allowed only when the package is not reachable from any production dependency)
//   everything else, including unknown or missing licenses, fails with the package list.
// The result is written to docs/licenses.md between generated markers (hand-written text is kept).
// Flags: --root <dir> (default: repo root), --docs <file> (default: <root>/docs/licenses.md), --no-write.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ALLOWED = [
  "Apache-2.0",
  "MIT",
  "MIT-0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "ISC",
  "0BSD",
  "Unlicense",
  "CC0-1.0",
  "BlueOak-1.0.0",
  "Python-2.0",
  "Zlib",
];
export const DEV_ONLY = ["MPL-2.0"];

export const START = "<!-- licenses:generated:start -->";
export const END = "<!-- licenses:generated:end -->";

// Verdict for one SPDX expression: "allowed" | "dev-only" | "violation".
// OR picks the best alternative, AND takes the worst.
export function classify(expression) {
  const rank = { allowed: 0, "dev-only": 1, violation: 2 };
  const single = (id) => {
    const t = id
      .trim()
      .replace(/^\(+|\)+$/g, "")
      .trim();
    if (ALLOWED.includes(t)) return "allowed";
    if (DEV_ONLY.includes(t)) return "dev-only";
    return "violation";
  };
  if (typeof expression !== "string" || expression.trim() === "") return "violation";
  const alternatives = expression.split(/\s+OR\s+/i).map((alt) => {
    const parts = alt.split(/\s+AND\s+/i).map(single);
    return parts.reduce((a, b) => (rank[b] > rank[a] ? b : a), "allowed");
  });
  return alternatives.reduce((a, b) => (rank[b] < rank[a] ? b : a), "violation");
}

const pnpmJson = (args, cwd) =>
  JSON.parse(
    execFileSync("pnpm", args, {
      cwd,
      encoding: "utf8",
      maxBuffer: 256 * 1024 * 1024,
      stdio: ["ignore", "pipe", "ignore"],
    }) || "{}",
  );

function flatten(byLicense) {
  const out = [];
  for (const [license, pkgs] of Object.entries(byLicense)) {
    for (const p of pkgs)
      for (const version of p.versions ?? ["unknown"]) out.push({ name: p.name, version, license });
  }
  return out;
}

// All installed packages; `devOnly` is true when no production dependency chain reaches them.
export function collect(root) {
  const all = flatten(pnpmJson(["-r", "licenses", "list", "--json"], root));
  const prod = new Set(
    flatten(pnpmJson(["-r", "licenses", "list", "--prod", "--json"], root)).map(
      (p) => `${p.name}@${p.version}`,
    ),
  );
  return all
    .map((p) => ({ ...p, devOnly: !prod.has(`${p.name}@${p.version}`) }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

export function evaluate(packages) {
  const violations = [];
  const devOnlyMpl = [];
  for (const p of packages) {
    const verdict = classify(p.license);
    if (verdict === "violation") violations.push(p);
    else if (verdict === "dev-only") (p.devOnly ? devOnlyMpl : violations).push(p);
  }
  return { violations, devOnlyMpl };
}

export function renderMarkdown(packages, { violations, devOnlyMpl }) {
  const counts = new Map();
  for (const p of packages) counts.set(p.license, (counts.get(p.license) ?? 0) + 1);
  const lines = [
    START,
    "",
    "## Installed dependency licenses (generated)",
    "",
    "Generated by `pnpm licenses:check`. Do not edit between the markers.",
    "",
  ];
  lines.push(`Packages scanned: ${packages.length}. Policy violations: ${violations.length}.`, "");
  lines.push("| License | Packages | Policy |", "|---|---|---|");
  for (const [license, n] of [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) {
    const v = classify(license);
    lines.push(
      `| ${license} | ${n} | ${v === "allowed" ? "allowed" : v === "dev-only" ? "dev-only" : "NOT ALLOWED"} |`,
    );
  }
  lines.push("", "### Development-only MPL-2.0 packages", "");
  if (devOnlyMpl.length === 0) lines.push("None.");
  else {
    lines.push("| Package | Version | License |", "|---|---|---|");
    for (const p of devOnlyMpl) lines.push(`| ${p.name} | ${p.version} | ${p.license} |`);
  }
  lines.push("", "### Violations", "");
  if (violations.length === 0) lines.push("None.");
  else {
    lines.push("| Package | Version | License |", "|---|---|---|");
    for (const p of violations)
      lines.push(`| ${p.name} | ${p.version} | ${p.license ?? "unknown"} |`);
  }
  lines.push("", "### Packages by license", "");
  const byLicense = new Map();
  for (const p of packages) byLicense.set(p.license, [...(byLicense.get(p.license) ?? []), p]);
  for (const [license, pkgs] of [...byLicense].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(
      `<details><summary>${license} (${pkgs.length})</summary>`,
      "",
      pkgs.map((p) => `\`${p.name}@${p.version}\``).join(", "),
      "",
      "</details>",
      "",
    );
  }
  lines.push(END, "");
  return lines.join("\n");
}

export function writeDocs(file, block) {
  let next;
  if (existsSync(file)) {
    const cur = readFileSync(file, "utf8");
    const s = cur.indexOf(START);
    const e = cur.indexOf(END);
    next =
      s !== -1 && e > s
        ? cur.slice(0, s) + block + cur.slice(e + END.length).replace(/^\n/, "")
        : `${cur.trimEnd()}\n\n${block}`;
  } else {
    next = `# Licenses\n\nPolicy: allowed ${ALLOWED.join(", ")}. MPL-2.0 is allowed for devDependencies only. Anything else or unknown fails \`pnpm licenses:check\`.\n\n${block}`;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, next);
}

export function main(argv) {
  const arg = (n, d) => (argv.includes(n) ? resolve(argv[argv.indexOf(n) + 1]) : d);
  const root = arg("--root", join(dirname(fileURLToPath(import.meta.url)), ".."));
  const docs = arg("--docs", join(root, "docs", "licenses.md"));
  const packages = collect(root);
  const result = evaluate(packages);
  if (!argv.includes("--no-write")) writeDocs(docs, renderMarkdown(packages, result));
  console.log(
    `licenses: ${packages.length} packages, ${result.devOnlyMpl.length} dev-only MPL-2.0, ${result.violations.length} violations`,
  );
  if (result.violations.length > 0) {
    console.error("License policy violations:");
    for (const p of result.violations)
      console.error(`  ${p.name}@${p.version}: ${p.license ?? "unknown"}`);
    return 1;
  }
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  process.exit(main(process.argv.slice(2)));
